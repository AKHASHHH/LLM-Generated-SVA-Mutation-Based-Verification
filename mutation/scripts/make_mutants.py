#!/usr/bin/env python3
"""Create the reference-as-DUT copy and the 10 controlled single-defect mutants.

Every mutant is the reference with exactly ONE textual edit (asserted to match exactly once),
plus the module rename apb_timer_ref -> apb_timer so it can be dropped in as the DUT.
These are CONTROLLED, INTENTIONAL defects. They are never to be reported as natural bugs.

Outputs:
  ref/apb_timer_refdut.sv           reference renamed to module apb_timer (no other change)
  mutants/Mxx_<name>.sv             mutant DUTs (module apb_timer)
  mutants/mutants.diff              unified diff of every mutant against the reference
  mutants/mutants.tsv               id, name, requirement, misconception (machine readable)
Usage: python3 make_mutants.py
"""
import difflib, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
REF = os.path.join(ROOT, "ref", "apb_timer_ref.sv")

MUTANTS = [
 ("M01", "PEND_CLEAR_BEATS_SET", "R-PRI-4, R-INT-2",
  "Software W1C clear given priority over the hardware expiration set of PEND.",
  "pend_n = expire ? 1'b1 : ((w_stat & PWDATA[0]) ? 1'b0 : pend);",
  "pend_n = (w_stat & PWDATA[0]) ? 1'b0 : (expire ? 1'b1 : pend);"),
 ("M02", "OVF_USES_POSTCLEAR_PEND", "R-INT-3",
  "OVF set condition looks at PEND after a same-cycle W1C clear instead of the held PEND.",
  "ovf_n  = (expire & pend) ? 1'b1",
  "ovf_n  = (expire & pend & ~(w_stat & PWDATA[0])) ? 1'b1"),
 ("M03", "RELOAD_USES_WRITTEN_LOAD", "R-TMR-11",
  "Periodic reload transfer takes the value being written to LOAD in the same cycle (new SHADOW) instead of the held SHADOW.",
  "if (!mode) begin active_n = shadow; count_n = shadow; end",
  "if (!mode) begin active_n = shadow_n; count_n = shadow_n; end"),
 ("M04", "SW_EN_BEATS_ONESHOT_COMPLETION", "R-PRI-2",
  "A coincident CTRL write of EN wins over the one-shot completion clearing EN.",
  "if (expire & mode)  en_n = 1'b0;\n        else if (w_ctrl)    en_n = PWDATA[0];",
  "if (w_ctrl)         en_n = PWDATA[0];\n        else if (expire & mode) en_n = 1'b0;"),
 ("M05", "LEVEL_SENSITIVE_START", "R-TMR-10, R-TMR-7",
  "Any CTRL write with EN=1 is treated as a start (reload + PCNT clear), even when already enabled.",
  "assign start  = w_ctrl & PWDATA[0] & ~en;",
  "assign start  = w_ctrl & PWDATA[0];"),
 ("M06", "START_KEEPS_PRESCALER_PHASE", "R-TMR-7",
  "A start reloads COUNT and ACTIVE but does not clear PCNT, so a re-enabled timer resumes its old prescaler phase.",
  "pcnt_n   = 8'd0;\n        end else if (en) begin",
  "pcnt_n   = rcmd ? 8'd0 : pcnt;\n        end else if (en) begin"),
 ("M07", "PRESCALER_EQUALITY_COMPARE", "R-TMR-13, R-TMR-1",
  "Tick uses PCNT == PSC instead of PCNT >= PSC, so lowering PSC below PCNT misses ticks until PCNT wraps.",
  "assign tick   = en & (pcnt >= psc);",
  "assign tick   = en & (pcnt == psc);"),
 ("M08", "RESTART_REQUIRES_EN", "R-TMR-9",
  "CMD.RESTART is ignored while the timer is stopped (EN=0).",
  "assign rcmd   = w_cmd  & PWDATA[0];",
  "assign rcmd   = w_cmd  & PWDATA[0] & en;"),
 ("M09", "IE_GATES_PEND", "R-INT-7, R-INT-1",
  "The interrupt-enable mask is applied to the status flag: expirations with IE=0 do not set PEND.",
  "pend_n = expire ? 1'b1 :",
  "pend_n = (expire & ie) ? 1'b1 :"),
 ("M10", "IRQ_REGISTERED", "R-INT-6",
  "irq is registered (APB-template habit), so it lags PEND & IE by one cycle.",
  "assign irq     = pend & ie;",
  "logic irq_q;\n    always_ff @(posedge PCLK or negedge PRESETn)\n        if (!PRESETn) irq_q <= 1'b0; else irq_q <= pend & ie;\n    assign irq     = irq_q;"),
]

def main():
    ref = open(REF).read()
    assert ref.count("module apb_timer_ref (") == 1
    hdr = ("// AUTO-GENERATED by scripts/make_mutants.py from ref/apb_timer_ref.sv - do not edit.\n")
    os.makedirs(os.path.join(ROOT, "mutants"), exist_ok=True)
    dut = ref.replace("module apb_timer_ref (", "module apb_timer (")
    open(os.path.join(ROOT, "ref", "apb_timer_refdut.sv"), "w").write(
        hdr + "// Reference implementation renamed to module apb_timer for use as the DUT. No other change.\n" + dut)
    diffs, tsv = [], ["id\tname\trequirement\tmisconception"]
    for mid, name, req, why, old, new in MUTANTS:
        n = ref.count(old)
        assert n == 1, f"{mid}: pattern matched {n} times"
        mut = dut.replace(old, new)
        banner = (hdr + f"// CONTROLLED MUTANT {mid}_{name}  (intentional single defect; NOT a natural bug)\n"
                  f"// Violates: {req}\n// Misconception: {why}\n")
        path = os.path.join(ROOT, "mutants", f"{mid}_{name}.sv")
        open(path, "w").write(banner + mut)
        diffs += difflib.unified_diff(dut.splitlines(True), mut.splitlines(True),
                                      fromfile="ref/apb_timer_refdut.sv", tofile=f"mutants/{mid}_{name}.sv", n=2)
        tsv.append(f"{mid}\t{name}\t{req}\t{why}")
    open(os.path.join(ROOT, "mutants", "mutants.diff"), "w").write("".join(diffs))
    open(os.path.join(ROOT, "mutants", "mutants.tsv"), "w").write("\n".join(tsv) + "\n")
    print(f"wrote ref/apb_timer_refdut.sv and {len(MUTANTS)} mutants")

if __name__ == "__main__":
    main()
